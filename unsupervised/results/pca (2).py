import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.datasets import load_iris
from sklearn.preprocessing import StandardScaler

from google.colab import drive
import os

drive.mount('/content/drive')

output_dir = "/content/drive/MyDrive/ML_Assignment_Outputs/pca"
os.makedirs(output_dir, exist_ok=True)
print("Results will be saved in:", output_dir)

#Load Iris dataset
iris = load_iris()
X_iris = iris.data
y_iris = iris.target
species = iris.target_names

print("Number of samples :", X_iris.shape[0])
print("Number of features:", X_iris.shape[1])
print("Feature names     :", iris.feature_names)
print("\nFirst 5 rows:")
display(pd.DataFrame(X_iris, columns=iris.feature_names).head())

# Standardize the feature
scaler_iris = StandardScaler()
X_std = scaler_iris.fit_transform(X_iris)

print("Shape of standardized data:", X_std.shape)
print("Feature means (should be ~0):", X_std.mean(axis=0).round(6))
print("Feature std devs (should be 1):", X_std.std(axis=0).round(6))

# Calculate covariance matrix
cov_matrix = np.cov(X_std, rowvar=False)

print("Covariance matrix (4 x 4):")
print(np.round(cov_matrix, 4))

# Calculate eigenvalues and eigenvectors
eigenvalues, eigenvectors = np.linalg.eigh(cov_matrix)

# Sort from largest to smallest
order = np.argsort(eigenvalues)[::-1]
eigenvalues = eigenvalues[order]
eigenvectors = eigenvectors[:, order]

print("Eigenvalues (largest to smallest):")
print(np.round(eigenvalues, 4))
print("\nEigenvectors (each COLUMN is one principal component direction):")
print(np.round(eigenvectors, 4))

# Explained variance
explained_variance_ratio = eigenvalues / np.sum(eigenvalues)
cumulative_variance = np.cumsum(explained_variance_ratio)

print("Explained variance ratio :", np.round(explained_variance_ratio, 4))
print("Cumulative variance      :", np.round(cumulative_variance, 4))

plt.figure(figsize=(7, 4.5))
plt.plot(range(1, 5), cumulative_variance, "o-")
plt.xticks(range(1, 5))
plt.xlabel("Number of principal components")
plt.ylabel("Cumulative explained variance")
plt.title("Cumulative Explained Variance (Iris)")
plt.grid(alpha=0.3)
plt.savefig(f"{output_dir}/cumulative_explained_variance.png", dpi=150, bbox_inches="tight")
plt.show()

X_pca_2 = X_std @ eigenvectors[:, :2]

print("Original standardized shape:", X_std.shape)
print("2-component shape          :", X_pca_2.shape)

X_pca_3 = X_std @ eigenvectors[:, :3]

print("Original standardized shape:", X_std.shape)
print("3-component shape          :", X_pca_3.shape)

plt.figure(figsize=(7, 5.5))
colors = ["tab:blue", "tab:orange", "tab:green"]
markers = ["o", "s", "^"]

for i, name in enumerate(species):
    mask = (y_iris == i)
    plt.scatter(X_pca_2[mask, 0], X_pca_2[mask, 1],
                c=colors[i], marker=markers[i], label=name, alpha=0.8, edgecolor="k")

plt.xlabel(f"PC1 ({explained_variance_ratio[0]*100:.1f}% variance)")
plt.ylabel(f"PC2 ({explained_variance_ratio[1]*100:.1f}% variance)")
plt.title("Iris Dataset: First Two Principal Components")
plt.legend()
plt.grid(alpha=0.3)
plt.savefig(f"{output_dir}/pca_scatter_pc1_pc2.png", dpi=150, bbox_inches="tight")
plt.show()

summary = []
summary.append("PCA SUMMARY (Iris, manual implementation)")
summary.append(f"Eigenvalues              : {np.round(eigenvalues, 4)}")
summary.append(f"Explained variance ratio : {np.round(explained_variance_ratio, 4)}")
summary.append(f"Cumulative variance      : {np.round(cumulative_variance, 4)}")
summary.append(f"Variance captured by first 2 PCs: {cumulative_variance[1]*100:.2f}%")
summary.append(f"Variance captured by first 3 PCs: {cumulative_variance[2]*100:.2f}%")
summary.append(f"Shape of 2-PC data: {X_pca_2.shape}")
summary.append(f"Shape of 3-PC data: {X_pca_3.shape}")

print("\n".join(summary))

# Save PCA results
with open(f"{output_dir}/pca_summary.txt", "w") as f:
    f.write("\n".join(summary))

np.savetxt(f"{output_dir}/covariance_matrix.csv", cov_matrix, delimiter=",")
np.savetxt(f"{output_dir}/eigenvalues.csv", eigenvalues, delimiter=",")
np.savetxt(f"{output_dir}/eigenvectors.csv", eigenvectors, delimiter=",")
np.savetxt(f"{output_dir}/X_pca_2.csv", X_pca_2, delimiter=",")
np.savetxt(f"{output_dir}/X_pca_3.csv", X_pca_3, delimiter=",")

print("\nAll files in output folder:", os.listdir(output_dir))

