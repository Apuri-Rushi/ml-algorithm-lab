    f.write(f"Decision Tree CV ROC-AUC : {dt_grid.best_score_:.4f}\n")
    f.write(f"SVM best params          : {svm_grid.best_params_}\n")
    f.write(f"SVM best CV ROC-AUC      : {svm_grid.best_score_:.4f}\n")

